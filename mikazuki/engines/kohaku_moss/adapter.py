"""Next Trainer form to a checked kogine Python config."""
from dataclasses import asdict, dataclass
from pathlib import Path
import math
import os
import re

SUPPORTED_FIELDS = {
    "model_train_type",
    "pretrained_model_name_or_path", "train_data_dir", "output_dir", "output_name",
    "max_train_steps", "max_train_epochs", "network_dim", "network_alpha",
    "network_algorithm", "learning_rate", "memory_profile", "mixed_precision",
    "save_every_n_steps", "sample_every_n_steps", "seed", "gpu_ids",
}
ALGORITHMS = {"lora", "locon", "loha", "lokr", "oft", "boft", "glora", "ia3", "dylora", "tlora"}
MEMORY_PROFILES = {"speed", "balanced", "low", "minimal", "auto"}


@dataclass
class AdaptedConfig:
    values: dict
    warnings: list[str]

    def as_dict(self):
        return asdict(self)


def _absolute(value, root):
    path = Path(str(value)).expanduser()
    return Path(os.path.abspath(path if path.is_absolute() else root / path))


def _integer(value, key, minimum=0):
    if isinstance(value, bool):
        raise ValueError(f"{key}: 必须为整数")
    try:
        result = int(value)
    except (TypeError, ValueError) as exc:
        raise ValueError(f"{key}: 必须为整数") from exc
    if result < minimum:
        raise ValueError(f"{key}: 必须不小于 {minimum}")
    return result


def adapt_config(config, runtime):
    unknown = sorted(key for key, value in config.items() if key not in SUPPORTED_FIELDS and value not in (None, ""))
    if unknown:
        raise ValueError("Unsupported KohakuMoss fields / 不支持的参数: " + ", ".join(unknown))
    required = ("pretrained_model_name_or_path", "train_data_dir", "output_dir", "output_name")
    missing = [key for key in required if not str(config.get(key) or "").strip()]
    if missing:
        raise ValueError("Missing required fields / 缺少必填项: " + ", ".join(missing))
    name = str(config["output_name"]).strip()
    if name in {".", ".."} or re.search(r'[<>:"/\\|?*\x00-\x1f]', name):
        raise ValueError("output_name: 请填写不含路径分隔符的文件名")
    steps = _integer(config.get("max_train_steps", 1000), "max_train_steps", 1)
    epochs = _integer(config.get("max_train_epochs", 0), "max_train_epochs")
    algorithm = str(config.get("network_algorithm") or "lora").lower()
    if algorithm not in ALGORITHMS:
        raise ValueError("network_algorithm: " + algorithm + " 暂不支持")
    profile = str(config.get("memory_profile") or "balanced")
    if profile not in MEMORY_PROFILES:
        raise ValueError("memory_profile: 请选择 speed/balanced/low/minimal/auto")
    precision = str(config.get("mixed_precision") or "bf16")
    if precision not in {"bf16", "fp16", "auto"}:
        raise ValueError("mixed_precision: 请选择 bf16/fp16/auto")
    values = {
        "WEIGHTS": str(_absolute(config["pretrained_model_name_or_path"], runtime.project_root)),
        "DATASETS": [{"source": "kohya", "path": str(_absolute(config["train_data_dir"], runtime.project_root)), "repeat_prefix": "first"}],
        "OUTPUT_DIR": str(_absolute(config["output_dir"], runtime.project_root)),
        "RUN_NAME": name,
        "STEPS": steps,
        "ALGO": algorithm,
        "DIM": _integer(config.get("network_dim", 32), "network_dim", 1),
        "ALPHA": float(config.get("network_alpha", config.get("network_dim", 32))),
        "LR": float(config.get("learning_rate", 1e-4)),
        "MEMORY_PROFILE": profile,
        "PRECISION": precision,
        "SAVE_EVERY": _integer(config.get("save_every_n_steps", 500), "save_every_n_steps"),
        "SAMPLE_EVERY": _integer(config.get("sample_every_n_steps", 0), "sample_every_n_steps"),
        "SEED": _integer(config.get("seed", 0), "seed"),
        "EXPORT_FORMATS": ("comfy", "lycoris"),
        "LOG_EVERY": 10,
    }
    if not math.isfinite(values["LR"]) or values["LR"] <= 0:
        raise ValueError("learning_rate: 必须为正数")
    warnings = [
        "实验性高性能引擎；请先用小步数验证输出。感谢 Kohaku / 龙娘与 LyCORIS 社区。",
    ]
    if epochs:
        warnings.append("KohakuMossTrainer 原生以 STEPS 驱动；当前 v1 保留 max_train_epochs 仅作 UI 备注，以 max_train_steps 为准。")
    return AdaptedConfig(values, warnings)


def dump_config(adapted, directory, run_id):
    path = Path(directory) / f"{run_id}-kohaku-moss.py"
    path.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        '"""Generated by Next Trainer for the pinned KohakuMossTrainer runtime."""',
        *[f"{key} = {value!r}" for key, value in adapted.values.items()],
        "",
    ]
    path.write_text("\n".join(lines), encoding="utf-8")
    return path.resolve()
